// Generates the public proof artifact: one real, signed Execution Package
// built from the qualified execution-package fixtures (#155, PRF-01..06).
//
// Everything is pinned so a clean clone regenerates byte-identical output:
// the fixture input and clock come from tests/helpers/execution-package-fixture
// (already pinned to 2026-07-15T15:00:00.000Z), and the Ed25519 key below is a
// committed TEST-ONLY fixture key. Ed25519 signing is deterministic (RFC 8032),
// so the signature bytes are reproducible.
//
//   corepack pnpm proof:generate
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import {
  ArtifactSealer,
  ExecutionPackageBuilder,
  NodeEd25519Signer,
  canonicalizeJson,
  createTrustRoot
} from "../packages/evidence/src/index.ts";
import { currentState, now, packageInput } from "../tests/helpers/execution-package-fixture.mjs";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

// TEST-ONLY fixture signing key (PKCS#8, Ed25519). It exists so the published
// artifact is reproducible; it signs fixture data only and carries no trust.
// Never reuse it for anything that is not this proof artifact.
const FIXTURE_KEY_PKCS8_BASE64 = "MC4CAQAwBQYDK2VwBCIEILXCi1ugPcQikUSpQdamwOhTy0OLf6VQqmq8cF7iv/Cs";
const FIXTURE_KEY_ID = "public-proof-fixture-2026";

export async function generateProofArtifact() {
  const signer = NodeEd25519Signer.fromPkcs8(
    { keyId: FIXTURE_KEY_ID, purposes: ["execution-package"] },
    Buffer.from(FIXTURE_KEY_PKCS8_BASE64, "base64")
  );
  const sealer = new ArtifactSealer({ signer, now: () => new Date(now) });
  const builder = new ExecutionPackageBuilder({ sealer });
  const trust = createTrustRoot({ trustRootId: "public-proof-root", version: 1, keys: [signer.publicKeyRef] });
  const input = packageInput();
  const sealed = await builder.build(input);
  const verification = await builder.verify(sealed, trust, currentState(input));
  if (!verification.ok) throw new Error("generated proof artifact failed its own verification");
  return {
    sealed,
    trust,
    json: `${canonicalizeJson(sealed)}\n`,
    markdown: renderMarkdown(sealed, verification)
  };
}

function renderMarkdown(sealed, verification) {
  return `# A real Execution Package

> **Fixture-generated, not a live run.** This artifact was built and signed by
> repository code from the same deterministic fixture input the qualified
> execution-package test suites use. No agent executed work to produce it:
> there is no Run Capsule, no gate execution record, and no signed Handoff
> here — those are the stages a live run adds. What you are inspecting is the
> real contract, envelope, derivation, and signature path, on fixture data.

Every claim on this site about Execution Packages can be checked against this
file. It was generated by
[\`scripts/generate-proof-artifact.mjs\`](../../scripts/generate-proof-artifact.mjs)
and any clean clone reproduces it byte-for-byte:

\`\`\`bash
corepack pnpm proof:generate
\`\`\`

A drift test regenerates the artifact on every gate run and fails if the
committed bytes and the generator disagree, so this page cannot silently rot.

## What the envelope proves

- **Content address** — \`artifactId\` is the SHA-256 of the unsigned artifact;
  renaming or editing any byte changes the id.
- **Binding** — \`bindingId\` is \`${sealed.bindingId}\`: the package is bound to
  one workspace, one feature, one version.
- **Derived work** — \`pendingTasks\` is computed from tasks and evidence, never
  authored; here the first pending task is
  \`${verification.firstPendingTaskId}\`.
- **Signature** — Ed25519 over the RFC 8785 canonical JSON of the envelope,
  by fixture key \`${sealed.keyId}\`. The raw canonical bytes live in
  [\`execution-package.json\`](../../docs/proof/execution-package.json).

## The artifact

\`\`\`json
${JSON.stringify(sealed, null, 2)}
\`\`\`
`;
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const { json, markdown } = await generateProofArtifact();
  await mkdir(resolve(ROOT, "docs", "proof"), { recursive: true });
  await writeFile(resolve(ROOT, "docs", "proof", "execution-package.json"), json);
  await writeFile(resolve(ROOT, "docs", "proof", "execution-package.md"), markdown);
  console.log("proof artifact written to docs/proof/");
}
